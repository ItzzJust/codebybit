import { defineConfig } from "oxlint";
import core from "ultracite/oxlint/core";
import jsPlugins from "ultracite/oxlint/js-plugins";
import react from "ultracite/oxlint/react";
import tanstack from "ultracite/oxlint/tanstack";
import tanstackJsPlugins from "ultracite/oxlint/tanstack/js-plugins";
import vitest from "ultracite/oxlint/vitest";

// ultracite's react config declares `react/react-compiler` which was removed
// in oxlint 1.79. Strip it so the config parses cleanly.
const { "react/react-compiler": _, ...patchedReactRules } = react.rules ?? {};
const patchedReact = { ...react, rules: patchedReactRules };

// oxlint's JS plugin bridge only loads plugins installed in this repo.
// `github` is intentionally dropped here, so its rules must be dropped too —
// keeping rules that reference a plugin that is never registered breaks the
// entire config ("Plugin 'github' not found").
const enabledJsPluginNames = new Set(["react-doctor", "sonarjs"]);
const enabledJsPluginRulePrefixes = new Set(["react-doctor", "sonarjs"]);

const keepSelectedPluginRules = <T extends Record<string, unknown>>(
  rules: T = {} as T
): T =>
  Object.fromEntries(
    Object.entries(rules).filter(([ruleName]) =>
      enabledJsPluginRulePrefixes.has(ruleName.split("/")[0] ?? ruleName)
    )
  ) as T;

const selectedJsPlugins = {
  ...jsPlugins,
  jsPlugins: jsPlugins.jsPlugins?.filter((plugin) =>
    enabledJsPluginNames.has(typeof plugin === "string" ? plugin : plugin.name)
  ),
  overrides: jsPlugins.overrides?.map((override) => ({
    ...override,
    rules: keepSelectedPluginRules(override.rules),
  })),
  rules: keepSelectedPluginRules(jsPlugins.rules),
};

export default defineConfig({
  extends: [
    core,
    patchedReact,
    tanstack,
    vitest,
    tanstackJsPlugins,
    selectedJsPlugins,
  ],
  ignorePatterns: [
    ...(core.ignorePatterns ?? []),
    // Generated by shadcn/ui; re-generating reintroduces issues
    "packages/ui/**",
    // Generated by beui.dev; re-generating reintroduces issues
    "**/components/motion/**",
    // Vendored AI tooling installed by OpenAgentsControl
    ".opencode/**",
  ],
  overrides: [
    {
      // TanStack file routes conventionally export `Route` at the top and
      // reference a component defined later in the file
      files: ["**/routes/**"],
      rules: {
        "eslint/no-use-before-define": "off",
      },
    },
  ],
  rules: {
    // shadcn/ui + BEUI generate `function` components; keeping them avoids
    // churn every time a component is re-generated
    "eslint/func-style": "off",
    // shadcn input-otp separator uses `<div role="separator">`
    "jsx-a11y/prefer-tag-over-role": "off",
    // Observer APIs (useSyncExternalStore subscribe, addEventListener) require
    // callbacks by design
    "promise/prefer-await-to-callbacks": "off",
    // Micro-perf rules that assume React Compiler / huge datasets; this
    // codebase favors readable, straightforward implementations
    "react-doctor/js-combine-iterations": "off",
    "react-doctor/js-set-map-lookups": "off",
    "react-doctor/react-compiler-no-manual-memoization": "off",
    // Vendored logo SVG uses high-precision path data; rounding distorts it
    "react-doctor/rendering-svg-precision": "off",
    "react/function-component-definition": "off",
    // TanStack file routes require GET/POST/... handler names
    "sonarjs/function-name": "off",
    // Filter data intentionally repeats labels/options (e.g. "Minecraft Version")
    "sonarjs/no-duplicate-string": "off",
    // shadcn components use wildcard imports (e.g. `import * as React`)
    "sonarjs/no-wildcard-import": "off",
    // Math.random is used for image-rotation jitter, not security
    "sonarjs/pseudo-random": "off",
  },
});
